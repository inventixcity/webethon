//! Schema-aware transfer format helpers. HTTP integration is not implemented yet.

use serde_json::{Map, Value, json};
use std::collections::HashSet;

pub const MAX_FILE_BYTES: usize = 4 * 1024 * 1024;
pub const MAX_ROWS: usize = 5_000;

#[derive(Debug, PartialEq)]
pub struct RowError {
    pub row: usize,
    pub errors: Vec<Value>,
}

#[derive(Debug, PartialEq)]
pub struct ParsedRows {
    pub rows: Vec<(usize, Value)>,
    pub failed: Vec<RowError>,
}

fn detail(path: &str, message: &str) -> Value {
    json!({"path": path, "message": message})
}

fn has_type(schema: &Value, kind: &str) -> bool {
    schema["type"] == kind
        || schema["type"]
            .as_array()
            .is_some_and(|types| types.iter().any(|item| item == kind))
}

fn cell(value: &str, schema: &Value) -> Result<Value, &'static str> {
    if has_type(schema, "string") {
        return Ok(Value::String(value.to_owned()));
    }
    let parsed: Value = serde_json::from_str(value).map_err(|_| "Enter a valid value.")?;
    if (parsed.is_null() && has_type(schema, "null"))
        || (parsed.is_boolean() && has_type(schema, "boolean"))
        || (parsed.is_number() && has_type(schema, "number"))
        || ((parsed.is_i64() || parsed.is_u64()) && has_type(schema, "integer"))
        || (parsed.is_array() && has_type(schema, "array"))
        || (parsed.is_object() && has_type(schema, "object"))
    {
        Ok(parsed)
    } else {
        Err("This value has the wrong type.")
    }
}

const PREFIX: &str = "__transfer.";
const DATA_PREFIX: &str = "__transfer.data.";
const VALUE_PREFIX: &str = "__transfer.value.";

fn csv_header(name: &str) -> String {
    if name.is_empty()
        || name.starts_with(PREFIX)
        || formula_safe(name) != name
        || matches!(name, "id" | "createdAt" | "updatedAt")
    {
        format!("{DATA_PREFIX}{name}")
    } else {
        name.to_owned()
    }
}
fn csv_value(value: Option<&Value>) -> String {
    match value {
        None => format!("{VALUE_PREFIX}missing"),
        Some(Value::Null) => format!("{VALUE_PREFIX}null"),
        Some(Value::String(s))
            if s.starts_with(VALUE_PREFIX)
                || s.starts_with('\'')
                || serde_json::from_str::<Value>(s).is_ok() =>
        {
            format!("{VALUE_PREFIX}string:{s}")
        }
        Some(Value::String(s)) => formula_safe(s),
        Some(v) => v.to_string(),
    }
}
fn export_cell(value: &str, schema: &Value) -> Result<Option<Value>, &'static str> {
    let value = if let Some(rest) = value.strip_prefix('\'') {
        if formula_safe(rest) == value {
            rest
        } else {
            value
        }
    } else {
        value
    };
    if value == format!("{VALUE_PREFIX}missing") {
        return Ok(None);
    }
    if value == format!("{VALUE_PREFIX}null") {
        return Ok(Some(Value::Null));
    }
    if let Some(s) = value.strip_prefix(&format!("{VALUE_PREFIX}json:")) {
        return serde_json::from_str(s)
            .map(Some)
            .map_err(|_| "Enter a valid value.");
    }
    if let Some(s) = value.strip_prefix(&format!("{VALUE_PREFIX}string:")) {
        return Ok(Some(Value::String(s.to_owned())));
    }
    if let Ok(parsed) = serde_json::from_str::<Value>(value)
        && ((parsed.is_boolean() && has_type(schema, "boolean"))
            || (parsed.is_number() && has_type(schema, "number"))
            || ((parsed.is_i64() || parsed.is_u64()) && has_type(schema, "integer"))
            || (parsed.is_array() && has_type(schema, "array"))
            || (parsed.is_object() && has_type(schema, "object")))
    {
        return Ok(Some(parsed));
    }
    cell(value, schema).map(Some)
}

/// Parse CSV data according to the entity's top-level property types.
/// Metadata columns generated by export are accepted but never imported.
pub fn parse_csv(bytes: &[u8], schema: &Value) -> Result<ParsedRows, &'static str> {
    if bytes.len() > MAX_FILE_BYTES {
        return Err("File is too large.");
    }
    let bytes = bytes.strip_prefix(&[0xef, 0xbb, 0xbf]).unwrap_or(bytes);
    std::str::from_utf8(bytes).map_err(|_| "File must be UTF-8.")?;
    let properties = schema["properties"]
        .as_object()
        .ok_or("Invalid entity schema.")?;
    let mut reader = csv::ReaderBuilder::new().from_reader(bytes);
    let headers = reader.headers().map_err(|_| "Invalid CSV header.")?.clone();
    let mut seen = HashSet::new();
    if headers.is_empty()
        || headers
            .iter()
            .any(|name| name.is_empty() || !seen.insert(name))
    {
        return Err("CSV headers must be present and unique.");
    }
    let exported = headers.iter().any(|h| h == "__transfer.meta.id")
        && headers.iter().any(|h| h == "__transfer.meta.createdAt")
        && headers.iter().any(|h| h == "__transfer.meta.updatedAt");
    let names: Vec<Option<&str>> = headers
        .iter()
        .map(|name| {
            if exported
                && matches!(
                    name,
                    "__transfer.meta.id"
                        | "__transfer.meta.createdAt"
                        | "__transfer.meta.updatedAt"
                )
            {
                None
            } else if exported {
                Some(name.strip_prefix(DATA_PREFIX).unwrap_or(name))
            } else if properties.contains_key(name) {
                Some(name)
            } else if matches!(name, "id" | "createdAt" | "updatedAt") {
                None
            } else {
                Some(name)
            }
        })
        .collect();
    let mut mapped = HashSet::new();
    if names.iter().flatten().any(|name| !mapped.insert(*name)) {
        return Err("CSV headers must map to unique fields.");
    }
    let unknown: Vec<Value> = names
        .iter()
        .flatten()
        .filter(|name| !properties.contains_key(**name))
        .map(|_| detail("file", "A column is not allowed."))
        .collect();
    if !unknown.is_empty() {
        for (index, record) in reader.records().enumerate() {
            if index >= MAX_ROWS {
                return Err("File has too many rows.");
            }
            record.map_err(|_| "Invalid CSV row.")?;
        }
        return Ok(ParsedRows {
            rows: vec![],
            failed: vec![RowError {
                row: 1,
                errors: unknown,
            }],
        });
    }
    let mut result = ParsedRows {
        rows: vec![],
        failed: vec![],
    };
    for (index, record) in reader.records().enumerate() {
        if index >= MAX_ROWS {
            return Err("File has too many rows.");
        }
        let record = record.map_err(|_| "Invalid CSV row.")?;
        let mut object = Map::new();
        let mut errors = Vec::new();
        for (name, value) in names.iter().zip(record.iter()) {
            if let Some(name) = name
                && let Some(property) = properties.get(*name)
            {
                let parsed = if exported {
                    export_cell(value, property)
                } else {
                    cell(value, property).map(Some)
                };
                match parsed {
                    Ok(Some(value)) => {
                        object.insert((*name).to_owned(), value);
                    }
                    Ok(None) => {}
                    Err(message) => errors.push(detail(name, message)),
                }
            }
        }
        let row = index + 2;
        if errors.is_empty() {
            result.rows.push((row, Value::Object(object)));
        } else {
            result.failed.push(RowError { row, errors });
        }
    }
    Ok(result)
}

/// Prefix spreadsheet formula triggers, including triggers following whitespace.
pub fn formula_safe(value: &str) -> String {
    if value.starts_with(['=', '+', '-', '@', '\t', '\r'])
        || value
            .trim_start_matches(' ')
            .starts_with(['=', '+', '-', '@', '\t', '\r'])
    {
        format!("'{value}")
    } else {
        value.to_owned()
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;

    fn schema() -> Value {
        json!({"properties": {"text": {"type":"string"}, "count": {"type":"integer"}, "tags": {"type":"array"}}})
    }

    #[test]
    fn csv_keeps_text_and_parses_arrays() {
        let result = parse_csv(
            b"\xef\xbb\xbftext,count,tags\n001,42,\"[\"\"a\"\"]\"\n",
            &schema(),
        )
        .unwrap();
        assert_eq!(
            result.rows[0].1,
            json!({"text":"001","count":42,"tags":["a"]})
        );
    }

    #[test]
    fn rejects_unknown_headers_and_bad_types() {
        assert!(
            !parse_csv(b"extra\nx\n", &schema())
                .unwrap()
                .failed
                .is_empty()
        );
        assert!(
            !parse_csv(b"count\nno\n", &schema())
                .unwrap()
                .failed
                .is_empty()
        );
    }

    #[test]
    fn exported_csv_round_trips_reserved_names_and_values() {
        let schema = json!({"properties": {"id":{"type":"string"}, "createdAt":{"type":"string"}, "__transfer.data.id":{"type":"string"}, "tags":{"type":"array"}, "text":{"type":"string"}, "quote":{"type":"string"}, "empty":{"type":["string","null"]}}});
        let data = json!({"id":"real id", "createdAt":"=formula", "__transfer.data.id":"__transfer.value.null", "tags":["a"], "text":" +2", "quote":"'=original", "empty":null});
        let fields: Vec<_> = schema["properties"]
            .as_object()
            .unwrap()
            .keys()
            .cloned()
            .collect();
        let mut writer = csv::Writer::from_writer(vec![]);
        writer
            .write_record(fields.iter().map(|x| csv_header(x)).chain([
                "__transfer.meta.id".into(),
                "__transfer.meta.createdAt".into(),
                "__transfer.meta.updatedAt".into(),
            ]))
            .unwrap();
        writer
            .write_record(fields.iter().map(|x| csv_value(data.get(x))).chain([
                "metadata".into(),
                "time".into(),
                "time".into(),
            ]))
            .unwrap();
        let bytes = writer.into_inner().unwrap();
        assert_eq!(parse_csv(&bytes, &schema).unwrap().rows[0].1, data);
    }

    #[test]
    fn exported_typed_cells_and_ambiguous_strings() {
        let schema = json!({"properties":{"n":{"type":"number"},"a":{"type":"array"},"b":{"type":"boolean"},"s":{"type":["string","number"]},"q":{"type":"string"},"m":{"type":"string"}}});
        let data = json!({"n":-12.5,"a":[1,"x"],"b":true,"s":"-12","q":"'=original","m":"__transfer.value.null"});
        assert_eq!(csv_value(data.get("n")), "-12.5");
        assert_eq!(csv_value(data.get("a")), "[1,\"x\"]");
        assert_eq!(csv_value(data.get("b")), "true");
        let names = ["n", "a", "b", "s", "q", "m"];
        let mut writer = csv::Writer::from_writer(vec![]);
        writer
            .write_record(names.into_iter().chain([
                "__transfer.meta.id",
                "__transfer.meta.createdAt",
                "__transfer.meta.updatedAt",
            ]))
            .unwrap();
        writer
            .write_record(
                names
                    .into_iter()
                    .map(|name| csv_value(data.get(name)))
                    .chain(["id".into(), "time".into(), "time".into()]),
            )
            .unwrap();
        assert_eq!(
            parse_csv(&writer.into_inner().unwrap(), &schema)
                .unwrap()
                .rows[0]
                .1,
            data
        );
    }

    #[test]
    fn spreadsheet_formulas_are_escaped() {
        for input in ["=1", "+1", "-1", "@x", "\tfoo", "\rfoo", " =1"] {
            assert!(formula_safe(input).starts_with('\''));
        }
        assert_eq!(formula_safe("normal"), "normal");
    }
}

